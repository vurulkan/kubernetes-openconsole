// Command docgen writes the docs site's reference pages from the code, so the
// lists on them (environment variables, permissions, audit events, metrics,
// Kubernetes RBAC, keyboard shortcuts) can't drift from what the app does.
// It only reads: descriptions live next to what they describe
// (config.Vars, api.FeatureDocs, rbac.ActionDocs, audit.*Docs, api.Metrics,
// the comments in deploy/rbac*.yaml, frontend/src/shortcuts.json).
//
// Run from backend/:  go run ./cmd/docgen   (writes ../docs/reference/*.md)
// CI runs it and fails on `git diff`; the docs site (vurulkan/openconsole-docs)
// copies the files from a tag of this repo.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type page struct {
	file, title, description string
	sources                  []string
	body                     func(root string) (string, error)
}

var pages = []page{
	{"environment-variables.md", "Environment variables", "Every environment variable the server reads, with its default.",
		[]string{"backend/internal/config/vars.go", "backend/internal/api/features.go", "Dockerfile", "deploy/deployment.yaml"}, envPage},
	{"permissions.md", "Application permissions", "Every resource and action a role can grant, what it opens and its endpoints.",
		[]string{"backend/internal/rbac", "backend/internal/api/openapi.yaml"}, permissionsPage},
	{"audit-events.md", "Audit events", "Every audit action, its outcomes, fields and details, with their ECS names.",
		[]string{"backend/internal/audit", "backend/internal/api", "backend/internal/recording"}, auditPage},
	{"metrics.md", "Metrics", "Every series on GET /metrics.",
		[]string{"backend/internal/api/observability.go"}, metricsPage},
	{"kubernetes-permissions.md", "Kubernetes permissions", "What OpenConsole's ClusterRole grants in each cluster, rule by rule.",
		[]string{"deploy/rbac.yaml", "deploy/rbac-readonly.yaml"}, kubeRBACPage},
	{"keyboard-shortcuts.md", "Keyboard shortcuts", "Every keyboard shortcut of the app.",
		[]string{"frontend/src/shortcuts.json"}, shortcutsPage},
}

func main() {
	root := flag.String("root", "..", "repository root")
	out := flag.String("out", "../docs/reference", "directory to write the pages to")
	flag.Parse()

	if err := os.MkdirAll(*out, 0o755); err != nil {
		fail(err)
	}
	keep := map[string]bool{}
	for _, p := range pages {
		body, err := p.body(*root)
		if err != nil {
			fail(fmt.Errorf("%s: %w", p.file, err))
		}
		var b strings.Builder
		fmt.Fprintf(&b, "---\ntitle: %q\ndescription: %q\n---\n\n", p.title, p.description)
		fmt.Fprintf(&b, "<!-- Generated by backend/cmd/docgen in vurulkan/kubernetes-openconsole from %s. Don't edit: change the source and run `go run ./cmd/docgen`. -->\n\n",
			strings.Join(p.sources, ", "))
		fmt.Fprintf(&b, "# %s\n\n%s", p.title, strings.TrimLeft(body, "\n"))
		text := strings.TrimRight(b.String(), "\n") + "\n"
		if err := os.WriteFile(filepath.Join(*out, p.file), []byte(text), 0o644); err != nil {
			fail(err)
		}
		keep[p.file] = true
	}
	// A page that is no longer generated must not linger.
	old, _ := filepath.Glob(filepath.Join(*out, "*.md"))
	for _, f := range old {
		if !keep[filepath.Base(f)] {
			_ = os.Remove(f)
		}
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "docgen:", err)
	os.Exit(1)
}

// cell makes s safe inside a Markdown table cell.
func cell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ")
}

func code(s string) string { return "`" + s + "`" }

// codeList renders values as `a`, `b`.
func codeList(vals []string) string {
	out := make([]string, len(vals))
	for i, v := range vals {
		out[i] = code(v)
	}
	return strings.Join(out, ", ")
}

func table(b *strings.Builder, header []string, rows [][]string) {
	b.WriteString("| " + strings.Join(header, " | ") + " |\n|")
	for range header {
		b.WriteString("---|")
	}
	b.WriteString("\n")
	for _, r := range rows {
		cells := make([]string, len(r))
		for i, c := range r {
			cells[i] = cell(c)
		}
		b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
	}
	b.WriteString("\n")
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
