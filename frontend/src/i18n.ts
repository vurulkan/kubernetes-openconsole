export const SUPPORTED_LOCALES = ['en', 'tr'] as const;
export type SupportedLocale = typeof SUPPORTED_LOCALES[number];

const STORAGE_KEY = 'uiLocale';

export function loadInitialLocale(): SupportedLocale {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && (SUPPORTED_LOCALES as readonly string[]).includes(stored)) {
      return stored as SupportedLocale;
    }
  } catch {
    /* ignore */
  }
  // Fall back to the browser language's two-letter code when it matches a
  // supported locale. First-time visitors on a TR browser land on TR; once
  // they pick EN, that choice persists and overrides the browser.
  const nav = (typeof navigator !== 'undefined' ? navigator.language : '').slice(0, 2);
  if ((SUPPORTED_LOCALES as readonly string[]).includes(nav)) {
    return nav as SupportedLocale;
  }
  return 'en';
}

export function persistLocale(locale: SupportedLocale) {
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    /* ignore */
  }
}

